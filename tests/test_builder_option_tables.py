from pathlib import Path
import sys
import unittest


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from v9_pro_builder import parse_data_report, parse_margin_ratio_provenance


class BuilderOptionTableTests(unittest.TestCase):
    def test_existing_data_report_option_tables_are_parsed(self):
        report = ROOT / "data_reports" / "DATA_REPORT_20261030.md"
        self.assertTrue(report.exists(), "Protected DATA_REPORT sample must remain available")
        parsed = parse_data_report(report)
        options = parsed["options"]

        self.assertGreaterEqual(len(options["instOpt"]), 3)
        self.assertGreaterEqual(len(options["instOptForce"]), 3)
        self.assertGreaterEqual(len(options["top10Call"]), 3)
        self.assertGreaterEqual(len(options["top10Put"]), 3)

        self.assertEqual(options["instOpt"][0][0], "外資")
        self.assertEqual(options["instOptForce"][0][0], "外資")
        # parse_markdown_tables preserves the Markdown header row at index 0.
        # Validate the first data row (index 1), not the generic header "項目".
        self.assertIn("買權", options["top10Call"][1][0])
        self.assertIn("賣權", options["top10Put"][1][0])


    def test_stale_margin_ratio_provenance_is_not_current_t0(self):
        # Use an explicit stale-source fixture. The checked-in DATA_REPORT is
        # regenerated by Fetch and may legitimately contain a current-T0 value.
        stale_row = (
            "| 融資維持率 | 178.40 | % | "
            "前值遞補 (DATA 2026-10-29；當日三源皆失敗；民間估算) |"
        )
        margin = parse_margin_ratio_provenance(stale_row, "2026-10-30")

        self.assertIsNotNone(margin["ratio"])
        self.assertEqual(margin["status"], "previous_report_fallback")
        self.assertEqual(margin["source_date"], "2026-10-29")
        self.assertFalse(margin["is_t0"])


if __name__ == "__main__":
    unittest.main()
